def fibonacci(n):
    a, b = 0, 1
    for _ in range(n):
        yield a
        a, b = b, a + b

# Используем генератор
for num in fibonacci(5):
    print(num)

"""Neste exemplo, o gerador Fibonacci calcula números sob demanda em vez de armazenar todos os valores na memória. Isto torna os geradores especialmente adequados para trabalhar com fluxos de dados ou sequências infinitas.

# **Outro modo de fazer o gerador**
"""

def factorial(n):
    if n == 0:
        return 1  # Базовый случай
    else:
        return n * factorial(n - 1)  # Рекурсивный вызов

print(factorial(5))  # Вывод: 120

