"""**O que é uma rede de decoradores e como usá-la**? O encadeamento de decoradores em Python é a aplicação sequencial de vários decoradores em uma única função. Cada decorador envolve uma função, adicionando ou alterando seu comportamento. Os decoradores são aplicados de cima para baixo, o que significa que o decorador superior é executado primeiro, depois o próximo e assim por diante. Exemplo de uma rede de decoradores"""

def decorator_one(func):
    def wrapper(*args, **kwargs):
        print("Decorator One")
        return func(*args, **kwargs)
    return wrapper

def decorator_two(func):
    def wrapper(*args, **kwargs):
        print("Decorator Two")
        return func(*args, **kwargs)
    return wrapper

@decorator_one
@decorator_two
def say_hello():
    print("Hello!")

say_hello()

